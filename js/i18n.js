(function () {
  var KEY = "vhp-lang";
  function get() { try { return localStorage.getItem(KEY) || "en"; } catch (e) { return "en"; } }
  window.vhpLang = get();
  window.t = function (k) { return (I18N[vhpLang] && I18N[vhpLang][k]) || I18N.en[k] || k; };
  window.applyI18n = function () {
    document.documentElement.lang = vhpLang;
    document.querySelectorAll("[data-i18n]").forEach(function (el) { el.textContent = t(el.dataset.i18n); });
    document.querySelectorAll("[data-i18n-ph]").forEach(function (el) { el.placeholder = t(el.dataset.i18nPh); });
    document.querySelectorAll("[data-vhp]").forEach(function (el) {
      var v = VHP[el.dataset.vhp]; el.textContent = typeof v === "object" ? v[vhpLang] : v;
    });
    document.querySelectorAll("a[data-tel]").forEach(function (a) { a.href = "tel:" + VHP.phoneHref; });
    document.querySelectorAll("a.map-link").forEach(function (a) { a.href = VHP.mapUrl; });
    document.querySelectorAll("a.fb-link").forEach(function (a) { a.href = VHP.facebook; });
    document.querySelectorAll("a.ig-link").forEach(function (a) { a.href = VHP.instagram; });
    document.dispatchEvent(new Event("langchange"));
  };
  window.toggleLang = function () {
    vhpLang = vhpLang === "en" ? "es" : "en";
    try { localStorage.setItem(KEY, vhpLang); } catch (e) {}
    applyI18n();
  };
  document.addEventListener("DOMContentLoaded", function () {
    document.querySelectorAll(".lang-btn").forEach(function (b) { b.addEventListener("click", toggleLang); });
    var m = document.querySelector(".menu-btn"), nav = document.querySelector(".nav-links");
    if (m && nav) m.addEventListener("click", function () {
      var open = nav.classList.toggle("open"); m.setAttribute("aria-expanded", open);
    });
    applyI18n();
  });
})();
